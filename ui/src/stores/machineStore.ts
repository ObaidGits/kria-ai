// ─── Types ─────────────────────────────────────────────────────────────────────

export type DeviceStatus = "online" | "offline" | "busy" | "error" | "enrolling";

/**
 * Enrollment request — mirrors the EXISTING `register_new_target` command
 * contract (camelCase fields, deserialized by the runtime). Task 9.1 does not
 * change this contract.
 */
export interface EnrollTargetRequest {
  displayName: string;
  host: string;
  port: number;
  username: string;
  sshPrivateKeyPath?: string;
  expectedHostkeySha256?: string;
}

export interface Device {
  id: string;
  name: string;
  type: "desktop" | "server" | "mobile" | "vm";
  status: DeviceStatus;
  os: string;
  lastSeen: number;
  ip?: string;
}

export interface RemoteSession {
  deviceId: string;
  active: boolean;
  resolution?: { width: number; height: number };
}

export type RemoteDesktopState =
  | "idle"
  | "pending_approval"
  | "active"
  | "stopped"
  | "expired";

/** Exact snapshot returned by the existing `remote_desktop_status` command. */
export interface RemoteDesktopStatus {
  state: RemoteDesktopState;
  session_id: string | null;
  started_at: number | null;
  last_activity: number | null;
  idle_timeout_secs: number;
  running: boolean;
  backend: string;
}

/** Exact public mobile-device record. Secrets never cross this boundary. */
export interface MobileDeviceInfo {
  id: string;
  name: string;
  created_at: number;
  last_seen: number;
  revoked: boolean;
}

/** Mobile gateway lifecycle snapshot from KRIA's desktop runtime. */
export interface MobileGatewayStatus {
  mobile_enabled: boolean;
  remote_desktop_enabled: boolean;
  running: boolean;
  bound_addr: string | null;
  device_count: number;
  remote_desktop: RemoteDesktopStatus;
}

/** Short-lived, single-use pairing challenge generated by KRIA. */
export interface MobilePairingChallenge {
  code: string;
  qr_payload: string;
  expires_at: number;
  server_url: string;
  mobile_url: string;
}

/** Preserve signal identity when poll responses contain no state change. */
export function sameRemoteDesktopStatus(
  left: RemoteDesktopStatus | null,
  right: RemoteDesktopStatus | null,
): boolean {
  if (left === right) return true;
  if (!left || !right) return false;
  return left.state === right.state
    && left.session_id === right.session_id
    && left.started_at === right.started_at
    && left.last_activity === right.last_activity
    && left.idle_timeout_secs === right.idle_timeout_secs
    && left.running === right.running
    && left.backend === right.backend;
}

export function sameMobileGatewayStatus(
  left: MobileGatewayStatus | null,
  right: MobileGatewayStatus | null,
): boolean {
  if (left === right) return true;
  if (!left || !right) return false;
  return left.mobile_enabled === right.mobile_enabled
    && left.remote_desktop_enabled === right.remote_desktop_enabled
    && left.running === right.running
    && left.bound_addr === right.bound_addr
    && left.device_count === right.device_count
    && sameRemoteDesktopStatus(left.remote_desktop, right.remote_desktop);
}

export function sameMobileDevices(
  left: readonly MobileDeviceInfo[],
  right: readonly MobileDeviceInfo[],
): boolean {
  return left === right || (left.length === right.length && left.every((device, index) => {
    const candidate = right[index];
    return device.id === candidate.id
      && device.name === candidate.name
      && device.created_at === candidate.created_at
      && device.last_seen === candidate.last_seen
      && device.revoked === candidate.revoked;
  }));
}

