/// One observable projection a caller derives from a policy world
/// (`mg-policy-pairs-v2`). Non-interference (MGR-004, design.md §5, V-POLICY-02)
/// requires the **unauthorized** projection of World A and World B to be
/// byte-identical: protected content must never alter any observable channel
/// (labels, IDs, counts, topology, timing). Every value here is defined by the
/// generator — the independent oracle — never derived from a system under test.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ObservableProjection {
    /// Sorted IDs of records visible to the caller.
    pub visible_record_ids: Vec<String>,
    /// Sorted labels visible to the caller.
    pub visible_labels: Vec<String>,
    /// Cardinality exposed to the caller (authorized count only).
    pub visible_count: usize,
    /// Sorted visible directed edges `"src->tgt"` between visible records.
    pub visible_edges: Vec<String>,
    /// Coarse timing bucket derived **only** from authorized (visible) work, so
    /// it can never encode hidden cardinality (V-POLICY-02).
    pub timing_bucket: String,
}

/// One planted per-channel non-interference case in the paired-world oracle.
/// Each isolates a single leakage channel and pins the exact authorized-vs-hidden
/// answer so tests can assert zero protected-data leak.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PairedChannelCase {
    /// Channel under test: `label`/`id`/`count`/`topology`/`timing`.
    pub dimension: String,
    /// Protected record/edge IDs responsible for the hidden content on this channel.
    pub protected_ids: Vec<String>,
    /// Protected markers (secret labels/IDs/edges/timing signals) that MUST NOT
    /// appear in any unauthorized projection.
    pub protected_markers: Vec<String>,
    /// The unauthorized caller's observable value on this channel in World A.
    pub unauthorized_value_a: String,
    /// The unauthorized caller's observable value on this channel in World B.
    pub unauthorized_value_b: String,
    /// The authorized caller's observable value on this channel in World B
    /// (reveals the protected content where explicitly authorized).
    pub authorized_value_b: String,
    /// MUST be `false`: a leak exists iff `unauthorized_value_a != unauthorized_value_b`.
    pub leaks: bool,
}

/// The paired-world non-interference oracle (`mg-policy-pairs-v2`). Two worlds
/// differ ONLY by protected content; an unauthorized caller must find them
/// observationally indistinguishable, while an authorized caller sees the
/// protected content in World B. Emitted only by the paired-world fixture;
/// omitted (`None`) elsewhere so other manifests are byte-unaffected.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PairedWorldOracle {
    /// Maximum sensitivity the unauthorized ("observer") caller may read.
    pub observer_max_sensitivity: i64,
    /// Maximum sensitivity the authorized caller may read.
    pub authorized_max_sensitivity: i64,
    /// The unauthorized caller's full observable projection of World A.
    pub unauthorized_projection_a: ObservableProjection,
    /// The unauthorized caller's full observable projection of World B
    /// (MUST equal [`Self::unauthorized_projection_a`]).
    pub unauthorized_projection_b: ObservableProjection,
    /// The authorized caller's full observable projection of World B
    /// (reveals protected content).
    pub authorized_projection_b: ObservableProjection,
    /// Planted per-channel cases (label/id/count/topology/timing).
    pub cases: Vec<PairedChannelCase>,
    /// Every protected marker that MUST NOT appear in any unauthorized output.
    pub forbidden_tokens: Vec<String>,
    /// Whether non-interference holds across every channel (MUST be `true`).
    pub non_interference_holds: bool,
}

