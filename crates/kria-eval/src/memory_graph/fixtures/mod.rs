/// A single graded relevance label: a document paired with its integer relevance
/// grade on the fixed scale `0` = not relevant, `1` = marginal, `2` = relevant,
/// `3` = highly relevant. Grades drive the graded gold set used for Recall@10 /
/// nDCG@10 evaluation (design.md §6, V-RET-03, MGR-036).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct GradedLabel {
    /// The judged document's ID.
    pub doc_id: String,
    /// Relevance grade in `0..=3`.
    pub grade: u8,
}

/// One judge's independent verdict over a query's candidate documents.
///
/// A "judge" here is a **deterministic, independent oracle rubric** defined by
/// the generator — there is no system under test, so the two rubrics label the
/// same candidates independently and their agreement (or adjudicated
/// disagreement) is what backs each query's gold judgment. This satisfies the
/// F0.2 "two judges OR recorded adjudication" requirement without any private
/// data or human-in-the-loop dependency.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct JudgeVerdict {
    /// Stable judge identity.
    pub judge_id: String,
    /// Human-readable description of the judge's deterministic rubric.
    pub rubric: String,
    /// Graded labels for every candidate, in stable `doc_id` order.
    pub labels: Vec<GradedLabel>,
}

/// A recorded adjudication decision, present iff the two judges disagree on any
/// candidate. The adjudicator is a third deterministic oracle rubric whose
/// resolved labels become the query's gold judgment. Its presence is the
/// alternative that satisfies "two judges OR recorded adjudication".
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct AdjudicationRecord {
    /// Stable adjudicator identity.
    pub adjudicator_id: String,
    /// Human-readable description of the adjudicator's deterministic rubric.
    pub rubric: String,
    /// Machine-stable rationale for the adjudication.
    pub rationale: String,
    /// The candidate `doc_id`s the two judges disagreed on.
    pub disagreement_doc_ids: Vec<String>,
    /// The adjudicated (gold) labels for every candidate, in `doc_id` order.
    pub resolved_labels: Vec<GradedLabel>,
}

/// One judged query in the corpus (`mg-retrieval-judged-v2`). Carries the two
/// independent judge verdicts, an optional adjudication record (on
/// disagreement), the graded gold set, the positive relevant set, and the
/// forbidden set that must be excluded 100%.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct JudgedQuery {
    /// Stable query ID.
    pub query_id: String,
    /// The query stratum (identifier/phrase/semantic/entity_relation/temporal/
    /// goal/contradiction/source/forbidden/adversarial).
    pub stratum: String,
    /// The design §6.2 deterministic query class this query maps to.
    pub query_class: String,
    /// Synthetic query text (no private data).
    pub query_text: String,
    /// Candidate document IDs judged for this query, in `doc_id` order.
    pub candidate_doc_ids: Vec<String>,
    /// The two independent judge verdicts.
    pub judges: Vec<JudgeVerdict>,
    /// Whether the two judges agreed on every candidate.
    pub judge_agreement: bool,
    /// Recorded adjudication decision (present iff `judge_agreement == false`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub adjudication: Option<AdjudicationRecord>,
    /// The graded gold labels for every candidate, in `doc_id` order.
    pub gold: Vec<GradedLabel>,
    /// Sorted IDs of positively-relevant documents (gold grade ≥ 1 and NOT
    /// forbidden) — the gold set for Recall@10 / nDCG@10.
    pub relevant_doc_ids: Vec<String>,
    /// Sorted IDs of relevant-but-forbidden documents that MUST be excluded
    /// (deleted/forgotten/policy-hidden/superseded) with 100% exclusion.
    pub forbidden_doc_ids: Vec<String>,
}

