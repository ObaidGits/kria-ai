/// Lower-case hex SHA-256 of `bytes`.
pub fn sha256_hex(bytes: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(bytes);
    hex_lower(&hasher.finalize())
}

/// Lower-case hex encoding.
pub fn hex_lower(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push_str(&format!("{b:02x}"));
    }
    s
}

/// Build [`FileEntry`] records for the data files and compute the package hash
/// (SHA-256 over the concatenation of ordered `<name>:<sha256>` lines).
pub fn package_files_and_hash(data_files: &[(String, Vec<u8>)]) -> (Vec<FileEntry>, String) {
    let mut entries = Vec::with_capacity(data_files.len());
    let mut acc = String::new();
    for (name, bytes) in data_files {
        let sha = sha256_hex(bytes);
        acc.push_str(name);
        acc.push(':');
        acc.push_str(&sha);
        acc.push('\n');
        entries.push(FileEntry {
            path: name.clone(),
            media_type: JSON_MEDIA_TYPE.to_string(),
            sha256: sha,
            size: bytes.len(),
        });
    }
    (entries, sha256_hex(acc.as_bytes()))
}

