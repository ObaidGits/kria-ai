//! Deterministic fixture generators for the Memory Graph Production Redesign
//! spec (gate F0.2 — "Freeze deterministic fixtures, seeds, and independent
//! judged corpus").
//!
//! This module hosts the **shared fixture-generator scaffolding** reused by
//! every `mg-*-v2` package plus the first concrete generator, [`unit_v2`]
//! (task 0.2.1, fixture `mg-unit-v2`, seed `0x4D475201`).
//!
//! ## Invariants (from `validation.md` §2 and gate F0.2)
//!
//! * **Fixed seeds.** Every generator is driven by the exact seed frozen in
//!   `validation.md`; nothing reads the wall clock, environment entropy, or the
//!   filesystem for its record content.
//! * **Independent oracle.** Expected memberships/answers are defined *by the
//!   generator itself* — the deterministic source of truth — never regenerated
//!   from a system under test. The authority store does not exist yet, so the
//!   generator is the only definition of the correct answer set.
//! * **Determinism.** Two runs of the same generator at the same
//!   [`GENERATOR_VERSION`] produce byte-identical files and therefore identical
//!   SHA-256 hashes.
//! * **Versioned, checksummed packages.** Each package emits a
//!   [`FixtureManifest`] carrying the generator version, seed, record counts by
//!   kind/policy/truth, the independent expected-membership hash, schema/model
//!   versions, per-file `{path, media_type, sha256, size}` records, and a
//!   package-level SHA-256.
//! * **No private data.** Generated content is synthetic; `manifest.contains_private_data`
//!   is always `false` and is asserted by tests.
//!
//! Generated packages are materialized under
//! `tests/fixtures/memory-graph/generated/<fixture-id>/<generator-version>/`.

