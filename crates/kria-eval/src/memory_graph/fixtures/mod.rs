/// (`mg-vector-oracle-v2`). Bytes are the canonical little-endian `f32`
/// serialization (the 1536-byte contract, design.md §6.1).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct VectorQuery {
    /// Pinned embedding model identity.
    pub model_id: String,
    /// Pinned model artifact hash.
    pub model_hash: String,
    /// Pinned tokenizer hash.
    pub tokenizer_hash: String,
    /// Vector dimension (`384`).
    pub dim: usize,
    /// Byte length (`1536`).
    pub byte_len: usize,
    /// Lower-case hex of the little-endian `f32` bytes.
    pub bytes_hex: String,
}

/// One planted candidate vector in the vector oracle. Bytes are the canonical
/// little-endian `f32` serialization; NaN/Inf are representable in bytes where
/// JSON floats are not, keeping the fixture faithful to the byte contract.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct VectorCandidate {
    /// Candidate record ID (also the stable tie-break key).
    pub record_id: String,
    /// Case code: `normalized`/`non_normalized`/`tie`/`zero`/`nan`/`inf`/
    /// `wrong_length`/`wrong_dimension`/`wrong_model`.
    pub case: String,
    /// Model identity declared for this candidate.
    pub model_id: String,
    /// Model artifact hash declared for this candidate.
    pub model_hash: String,
    /// Tokenizer hash declared for this candidate.
    pub tokenizer_hash: String,
    /// Declared vector dimension (may be wrong for reject cases).
    pub declared_dim: usize,
    /// Actual byte length of `bytes_hex` (may be wrong for reject cases).
    pub byte_len: usize,
    /// Lower-case hex of the little-endian `f32` bytes.
    pub bytes_hex: String,
    /// Whether the candidate is accepted for scoring (decodes to 384 finite
    /// `f32`, nonzero norm, matching model).
    pub valid: bool,
    /// Machine-stable rejection reason when `valid == false`.
    pub reject_reason: Option<String>,
    /// Independently-computed expected cosine (f64) when `valid == true`.
    pub expected_cosine: Option<f64>,
}

/// One entry in the expected exact-search ranking.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct RankedVector {
    /// One-based rank in the expected ordering.
    pub rank: usize,
    /// The ranked candidate's record ID.
    pub record_id: String,
    /// The independently-computed cosine score (f64).
    pub cosine: f64,
}

/// One rejected candidate with its reason code.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RejectedVector {
    /// The rejected candidate's record ID.
    pub record_id: String,
    /// Machine-stable rejection reason.
    pub reason: String,
}

/// The vector oracle (`mg-vector-oracle-v2`). Defines the exact `f64` cosine
/// score for every acceptable candidate, the stable score-desc/record-ID
/// ranking, the tie groups, and the rejection outcomes for every ill-formed
/// vector (design.md §6.1, V-VECTOR-01). Emitted only by the vector fixture;
/// omitted (`None`) elsewhere so other manifests are byte-unaffected.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct VectorOracle {
    /// Pinned embedding model identity.
    pub model_id: String,
    /// Pinned model artifact hash.
    pub model_hash: String,
    /// Pinned tokenizer hash.
    pub tokenizer_hash: String,
    /// Vector dimension (`384`).
    pub dim: usize,
    /// Vector byte length (`1536`).
    pub vector_byte_len: usize,
    /// The exact cosine formula the oracle computes.
    pub cosine_formula: String,
    /// The numeric accumulation type (`f64`).
    pub accumulation: String,
    /// The tie-break rule (`score desc, then record_id asc`).
    pub tie_break: String,
    /// Number of ranked entries returned (the full acceptable set).
    pub top_k: usize,
    /// The query vector.
    pub query: VectorQuery,
    /// Expected ranking over acceptable candidates (rank 1 = best).
    pub ranking: Vec<RankedVector>,
    /// Groups of record IDs sharing an identical cosine, each in tie-break order.
    pub tie_groups: Vec<Vec<String>>,
    /// Rejected candidates with reason codes.
    pub rejected: Vec<RejectedVector>,
}

