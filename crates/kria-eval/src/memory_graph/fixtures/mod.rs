// Deterministic PRNG (SplitMix64)
// ---------------------------------------------------------------------------

/// A tiny, fully-specified, portable PRNG. SplitMix64 has a fixed algorithm, so
/// its output depends only on the seed — guaranteeing byte-identical fixtures
/// across machines and toolchain versions (unlike `rand`'s `StdRng`).
#[derive(Debug, Clone)]
pub struct SplitMix64 {
    state: u64,
}

impl SplitMix64 {
    /// Seed the generator with the frozen fixture seed.
    pub fn new(seed: u64) -> Self {
        Self { state: seed }
    }

    /// Next pseudo-random `u64`.
    pub fn next_u64(&mut self) -> u64 {
        self.state = self.state.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.state;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }

    /// Uniform-ish value in `0..n` (bias is negligible for fixture sizes).
    pub fn below(&mut self, n: usize) -> usize {
        (self.next_u64() % n as u64) as usize
    }

    /// A canonical lower-case hyphenated UUID-shaped identifier built from 16
    /// deterministic bytes. Not a real v4 UUID (bits are not forced) but stable
    /// and canonically formatted, which is all the fixture requires.
    pub fn next_uuid(&mut self) -> String {
        let a = self.next_u64();
        let b = self.next_u64();
        let bytes = [a.to_be_bytes(), b.to_be_bytes()].concat();
        format!(
            "{:02x}{:02x}{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}-{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}",
            bytes[0], bytes[1], bytes[2], bytes[3], bytes[4], bytes[5], bytes[6], bytes[7],
            bytes[8], bytes[9], bytes[10], bytes[11], bytes[12], bytes[13], bytes[14], bytes[15],
        )
    }
}

